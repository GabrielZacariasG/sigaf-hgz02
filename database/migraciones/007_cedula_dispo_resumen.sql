-- Crea:
--   dispo_cortes          un renglón por día cargado (totales de la unidad 10102)
--   dispo_mensual         historia diaria por cuenta y mes (2026M01..M12), sumando centros de costo
--   dispo_detalle_actual  el corte MÁS RECIENTE completo: cuenta × centro de costo × proyecto × mes
--   cedula_bloques        orden y bloques de la hoja "resumen" de la cédula (158 cuentas)
--   presupuesto_inicial   presupuesto inicial 2026 por cuenta (hoja "pto", 105 cuentas)
-- Permisos: leer = cualquier usuario con sesión; escribir = personal de Finanzas (fn_es_personal).
-- No toca tablas existentes. Cómo: SQL Editor de Supabase → Run.
-- =====================================================================
create table if not exists dispo_cortes (
  fecha            date primary key,
  archivo          text,
  filas            integer,
  presupuesto      numeric(16,2) not null default 0,
  gasto            numeric(16,2) not null default 0,
  comprometido     numeric(16,2) not null default 0,
  precomprometido  numeric(16,2) not null default 0,
  disponible       numeric(16,2) not null default 0,
  cargado_por      uuid default auth.uid(),
  cargado_at       timestamptz not null default now()
);

create table if not exists dispo_mensual (
  fecha            date not null references dispo_cortes(fecha) on delete cascade,
  cuenta_finat     text not null,
  periodo          text not null,            -- 2026M01 .. 2026M12
  presupuesto      numeric(16,2) not null default 0,
  gasto            numeric(16,2) not null default 0,
  comprometido     numeric(16,2) not null default 0,
  precomprometido  numeric(16,2) not null default 0,
  disponible       numeric(16,2) not null default 0,
  primary key (fecha, cuenta_finat, periodo)
);
create index if not exists dispo_mensual_cuenta on dispo_mensual (cuenta_finat, fecha);

create table if not exists dispo_detalle_actual (
  fecha            date not null,
  cuenta_finat     text not null,
  centro_costo     text not null,
  proyecto         text not null default '',
  periodo          text not null,
  presupuesto      numeric(16,2) not null default 0,
  gasto            numeric(16,2) not null default 0,
  comprometido     numeric(16,2) not null default 0,
  precomprometido  numeric(16,2) not null default 0,
  disponible       numeric(16,2) not null default 0
);
create index if not exists dispo_detalle_cuenta on dispo_detalle_actual (cuenta_finat, centro_costo);

create table if not exists cedula_bloques (
  orden        integer primary key,
  bloque       text not null,      -- nombre del TOTAL en la cédula
  grupo        text,               -- TOTAL AREA MEDICA / Total Servicios / ...
  cuenta_prei  text,
  cuenta_finat text,
  nombre       text
);

create table if not exists presupuesto_inicial (
  anio         integer not null,
  cuenta_finat text not null,
  cuenta_prei  text,
  nombre       text,
  importe      numeric(16,2) not null,
  fuente       text,
  primary key (anio, cuenta_finat)
);

